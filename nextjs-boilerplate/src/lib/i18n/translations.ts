/**
 * Translate a key to the given locale.
 * Falls back to English, then Czech if translation is missing.
 */
export function t(key: TranslationKey, locale: string): string {
  const map = T[key];
  return map[locale as Locale] ?? map['en'] ?? map['cs'] ?? key;
}

/**
 * Returns a bound translate function for a given locale.
 * Useful in components: const tr = useTranslations(locale)
 */
export function makeTranslator(locale: string) {
  return (key: TranslationKey): string => t(key, locale);
}
